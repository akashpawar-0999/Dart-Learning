void main() {
  // ================================================================
  // TOPIC 1.1 — int
  // ================================================================
  // int is used to store whole numbers.
  // Examples:
  // 10
  // 20
  // -5
  // 1000
  // ================================================================

  // Create a variable named age that stores a whole number.
  int age = 20;

  // Print the value stored inside age.
  // Output: 20
  print(age);

  // Change the value stored inside age.
  age = 21;

  // Print the updated value.
  // Output: 21
  print(age);

  // Create another integer.
  int marks = 95;

  // Output: 95
  print(marks);

  // Perform arithmetic with integers.
  int a = 10;
  int b = 5;

  // Addition.
  // Output: 15
  print(a + b);

  // Subtraction.
  // Output: 5
  print(a - b);

  // Output: -5
  print(b - a);

  // Multiplication.
  // Output: 50
  print(a * b);

  // Integer division using ~/.
  // Output: 2
  print(a ~/ b);

  // Output: 2.0
  print(a / b);

  // Output: 0.5
  print(b / a);

  // Output: 0
  print(b ~/ a);


}