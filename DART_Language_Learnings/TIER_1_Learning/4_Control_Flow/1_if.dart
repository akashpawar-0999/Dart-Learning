void main() {
  // ================================================================
  // TOPIC 4 — CONTROL FLOW
  // FILE 1 — if
  // ================================================================

  // Store the user's age.
  int age = 20;

  // Check whether age is 18 or greater.
  if (age >= 18) {
    // Output: You are an adult.
    print("You are an adult.");
  }


  // ================================================================
  // ANOTHER EXAMPLE
  // ================================================================

  // Store the user's marks.
  int marks = 80;

  // Check whether marks are greater than or equal to 40.
  if (marks >= 40) {
    // Output: You passed.
    print("You passed.");
  }


  // ================================================================
  // BOOLEAN WITH if
  // ================================================================

  // Store login status.
  bool isLoggedIn = true;

  // Execute when isLoggedIn is true.
  if (isLoggedIn) {
    // Output: Welcome!
    print("Welcome!");
  }
}
