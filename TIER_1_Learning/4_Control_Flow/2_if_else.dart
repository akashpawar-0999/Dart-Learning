void main() {
  // ================================================================
  // FILE 2 — if / else
  // ================================================================

  // Store the user's age.
  int age = 16;

  // Check whether the user is an adult.
  if (age >= 18) {
    // This runs when age is 18 or greater.
    print("You are an adult.");
  } else {
    // This runs when age is less than 18.
    // Output: You are not an adult.
    print("You are not an adult.");
  }


  // ================================================================
  // ANOTHER EXAMPLE
  // ================================================================

  // Store marks.
  int marks = 35;

  // Check whether the student passed.
  if (marks >= 40) {
    // Output if condition is true.
    print("Pass");
  } else {
    // Output: Fail
    print("Fail");
  }
}
