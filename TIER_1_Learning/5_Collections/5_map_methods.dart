void main() {
  // ================================================================
  // FILE 5 — MAP METHODS
  // ================================================================


  // Create a Map.
  Map<String, int> marks = {
    "Math": 90,
    "Science": 85,
    "English": 80,
  };


  // ================================================================
  // KEYS
  // ================================================================

  // Get all keys.
  // Output: (Math, Science, English)
  print(marks.keys);


  // ================================================================
  // VALUES
  // ================================================================

  // Get all values.
  // Output: (90, 85, 80)
  print(marks.values);


  // ================================================================
  // LENGTH
  // ================================================================

  // Output: 3
  print(marks.length);


  // ================================================================
  // containsKey()
  // ================================================================

  // Output: true
  print(marks.containsKey("Math"));


  // ================================================================
  // containsValue()
  // ================================================================

  // Output: true
  print(marks.containsValue(90));


  // ================================================================
  // ADD / UPDATE
  // ================================================================

  // Add a new subject.
  marks["Computer"] = 95;

  // Output: 95
  print(marks["Computer"]);


  // Update Math marks.
  marks["Math"] = 100;

  // Output: 100
  print(marks["Math"]);


  // ================================================================
  // remove()
  // ================================================================

  // Remove English.
  marks.remove("English");

  // Output: {Math: 100, Science: 85, Computer: 95}
  print(marks);


  // ================================================================
  // isEmpty / isNotEmpty
  // ================================================================

  // Output: false
  print(marks.isEmpty);

  // Output: true
  print(marks.isNotEmpty);
}
